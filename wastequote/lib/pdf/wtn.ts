// Draft waste transfer note, pre-filled from the accepted quote. Its fields
// follow the UK duty-of-care waste transfer note (sections A-D); in Spain
// the equivalent is the documento de identificación (RD 553/2020). It is a
// draft for the salesperson and the customer to check, not a legal document.
import { company, containerById, ewcByCode, frequencyById, materialById } from "../data";
import type { QuoteRecord } from "../quote";
import { A4, C, M, box, hr, label, newKit, text } from "./kit";

export async function wtnPdf(q: QuoteRecord): Promise<Uint8Array> {
  const k = await newKit(`Draft waste transfer note ${q.number}`);
  const ev = q.evaluation;
  const s = ev.stream;
  const chosen = ev.routes.find((r) => r.route === q.chosenRoute)!;
  const material = materialById(s.material)!;
  const container = containerById(ev.config.containerId)!;
  const freq = frequencyById(ev.config.frequencyId)!;
  const ewc = ewcByCode(s.ewc);
  const W = A4.w - 2 * M;
  const perLift = ev.capacity.tonnesPerLift;

  // watermark-ish draft band
  box(k, 0, A4.h - 30, A4.w, 30, C.flagSoft);
  text(k, "DRAFT · not valid until completed and signed by both parties", M, A4.h - 19, { size: 8, font: k.bold, color: C.flag });

  let y = A4.h - 62;
  text(k, "Waste transfer note", M, y, { size: 18, font: k.bold });
  text(k, `Ref. ${q.number}-WTN · season ticket for repeated transfers of the same waste`, M, y - 16, { size: 8.5, color: C.ink2 });
  y = text(
    k,
    "Fields follow the UK duty-of-care waste transfer note (Sections A-D). For transfers in Spain use the documento de identificación (Real Decreto 553/2020); the same data applies.",
    M,
    y - 30,
    { size: 7.5, color: C.muted, maxWidth: W },
  );
  y -= 4;

  const section = (title: string, rows: Array<[string, string]>) => {
    y -= 24;
    hr(k, y + 10, M, A4.w - M, C.ink, 1);
    text(k, title, M, y, { size: 10, font: k.bold });
    y -= 6;
    for (const [kk, v] of rows) {
      y -= 15;
      label(k, kk, M, y + 4);
      const next = text(k, v || "____________________________", M + 170, y + 4, { size: 9, maxWidth: W - 170 });
      y = Math.min(y, next + 11);
    }
  };

  section("Section A · Description of the waste", [
    ["EWC / List of Waste code", `${s.ewc} · ${ewc?.description ?? ""}${ewc?.hazardous ? " (hazardous)" : " (non-hazardous)"}`],
    ["Description", `${material.name}. ${q.vision.result.summary}`],
    ["Contamination", `${s.contamination}: ${material.contamination[s.contamination]}`],
    ["How is the waste contained?", `${ev.config.containerCount} × ${container.name}, emptied ${freq.name.toLowerCase()}`],
    ["Quantity", `Estimated ${perLift.toFixed(2)} t per lift (${s.volumePerWeekM3} m³/week). Actual weight from weighbridge ticket.`],
    ["Process producing the waste", `${q.customer.nace || "____"} · ${q.customer.company}`],
    [
      "Waste hierarchy declaration",
      `[  ] I confirm I have applied the waste hierarchy. Proposed route: ${chosen.routeName.toLowerCase()} (${chosen.treatmentName.toLowerCase()}).`,
    ],
  ]);

  section("Section B · Current holder of the waste (transferor)", [
    ["Name", q.customer.company],
    ["Address of the site", q.customer.site],
    ["Contact", q.customer.contact],
    ["Holder is", "[  ] producer   [  ] importer   [  ] local authority   [  ] other: ________"],
  ]);

  section("Section C · Person collecting the waste (transferee)", [
    ["Name", company.seller.name],
    ["Address", company.seller.address],
    ["Carrier registration", company.seller.carrier_registration],
    ["Waste manager / permit no.", company.seller.waste_manager_registration],
    ["Destination", `${chosen.facilityName} · operation ${chosen.rdCode}`],
  ]);

  section("Section D · The transfer", [
    ["Address of transfer", q.customer.site],
    ["Date(s) of transfer", `From ________ for 12 months (${freq.name.toLowerCase()})`],
    ["Broker or dealer (if any)", "None"],
  ]);

  y -= 34;
  const half = W / 2 - 10;
  hr(k, y, M, M + half, C.ink2);
  hr(k, y, M + half + 20, A4.w - M, C.ink2);
  text(k, "Transferor signature, name, date", M, y - 11, { size: 7.5, color: C.muted });
  text(k, "Transferee signature, name, date", M + half + 20, y - 11, { size: 7.5, color: C.muted });

  text(
    k,
    "Generated by WasteQuote from the accepted quote. The seller, carrier and permit numbers above are sample values for the demo company; replace them with real registrations before use.",
    M,
    44,
    { size: 6.5, color: C.muted, maxWidth: W },
  );
  return k.doc.save();
}
